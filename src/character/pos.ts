/**
 * 메가폰트 캐릭터가 지금 어디에 있는지.
 *
 * 구경꾼들이 따라다니려면 매 프레임 그 자리를 알아야 하는데, 캐릭터의
 * 위치는 React 상태가 아니다 — 초당 60번 상태를 갱신하면 홈 전체가 그만큼
 * 다시 그려진다(HomeCharacter의 주석). 그래서 값 하나를 이 모듈이 들고
 * 있고, 캐릭터가 그릴 때 적고 구경꾼이 그릴 때 읽는다.
 *
 * 프레임 좌표계다(.home-frame의 왼쪽 위가 0,0). 두 쪽 다 같은 상자 안에
 * 있으므로 변환이 필요 없다.
 */
export const charPos = {
  /** 상자 한가운데의 자리 */
  x: 0,
  y: 0,
  /** 지금 화면에서 차지하는 한 변 (부풀기까지 곱한 값) */
  size: 0,
  /**
   * 그림자가 놓인 줄 — 이 캐릭터의 **바닥**이다.
   *
   * 메가폰트는 공중에 떠 있으므로 몸 아래가 아니라 그림자가 바닥을 정한다.
   * 구경꾼은 제 발끝을 이 줄과 견줘 앞뒤를 정한다: 아래면 앞, 위면 뒤.
   */
  ground: 0,
  /**
   * 손에 들려 바닥에서 떠오른 높이(px). 0이면 제자리다.
   *
   * 자리(x·y·ground)는 들려도 그대로다 — 그림자가 바닥에 남고, 구경꾼은
   * 그 바닥을 기준으로 앞뒤를 가른다. 들린 것을 알아야 하는 쪽(구경꾼이
   * 올려다보는 것)은 이 값을 본다.
   */
  lift: 0,
  /**
   * 나팔이 향한 쪽 (-1 왼쪽 · +1 오른쪽).
   *
   * 작은 하늘색 삼각형이 입을 대는 쪽이고 붉은 삼각형이 나팔이다. 포즈
   * 이름과 반대다 — 'left'는 입이 왼쪽이라 **소리는 오른쪽으로** 나간다.
   */
  voice: 1 as 1 | -1,
  /** 첫인사가 끝났는가. 나팔에서 말이 나오는 것은 그 뒤부터다 */
  greeted: false,
  /** 캐릭터가 아직 자리를 잡기 전이면 false — 구경꾼은 그동안 안 나온다 */
  ready: false
};
