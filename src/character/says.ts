/**
 * 구경꾼이 방금 한 말.
 *
 * 홈에 떠다니는 말은 시계가 띄우고 있었다 — 메가폰트가 돌아서고 3.2초 뒤에
 * 첫 마디, 그 뒤로는 3.4~7초마다 하나씩. 그러면 **누가 한 말인지가 없다.**
 * 걷던 사람이 메가폰트 앞에서 빨개지는 것과 화면에 글이 뜨는 것이 서로
 * 모르는 채 따로 돌았다.
 *
 * 이제 차례가 하나다:
 *
 *   들어온다 → 메가폰트 앞에 선다 → 하늘색이 빨강이 된다 → 그때 말이 뜬다
 *
 * HomeCrowd가 빨개지는 순간 여기에 자리를 적고, HomeVoices가 프레임마다
 * 비워 가며 그 자리에서 말을 띄운다. charPos와 같은 얼개다 — 초당 예순 번
 * 상태를 올리면 홈 전체가 그만큼 다시 그려지므로, 모듈 하나를 같이 쓴다.
 */
export const says = {
  /**
   * 아직 안 띄운 자리들. 액자 좌표다(.home-frame의 왼쪽 위가 0,0).
   * x는 몸의 한가운데, top은 **머리 끝**이다 — 말은 그 위에 선다.
   */
  queue: [] as Array<{ x: number; top: number }>,
  /** 몇 번째 말인가. 0이면 아직 아무도 말하지 않았다 — 그 첫 말이 인사다 */
  count: 0
};

/** 빨개진 자리를 적어 둔다 */
export function said(x: number, top: number) {
  /* 쌓아 두지 않는다. 한꺼번에 여럿이 빨개져도 글이 우르르 뜨면 한 사람의
     말로 안 읽힌다 — 셋까지만 들고 나머지는 버린다. (재서 확인: 70초에
     열셋, 제일 촘촘할 때 0.4초 간격이다) */
  if (says.queue.length < 3) says.queue.push({ x, top });
}
