// 벽의 물리 사양과 시간. 화면 카피와 필터가 같은 숫자를 봐야 해서 여기 모은다.

/**
 * 실제 디스플레이 — 2.5 × 1.41 m, Full HD 1920×1080 (16:9).
 *
 * 2026-09-22까지 2.4 × 1.5 (16:10)로 적혀 있었다. 실물을 확인하니 16:9고,
 * 2.5m 폭에 16:9면 높이가 1.40625m — 재어 온 1.4와 맞는다. 픽셀과 물리가
 * 같은 비율이라 화면에서는 16/9로 쓰면 된다.
 *
 * 비율이 납작해지면서 같은 vh가 더 작아진다 — 16:10에서 72vh는 폭의 45%,
 * 16:9에서는 40.5%다. 그래서 강조·잔상의 크기를 같이 올렸다(WallSimulation).
 */
export const WALL_W_M = 2.5;
export const WALL_H_M = 1.40625;

/**
 * 벽에 머무는 기간.
 * 별도의 아카이브는 두지 않는다 — 이 사흘 동안 풍경에 떠 있는 것이 곧 기록이고,
 * 지나면 남지 않는다. 사라짐이 이 장치의 성질이다.
 */
export const STAY_DAYS = 3;
export const STAY_MS = STAY_DAYS * 24 * 60 * 60 * 1000;

/**
 * 폰이 홈에 꽂혀 있는 동안 그 한 줄만 벽을 통째로 차지한다.
 *
 * 이 숫자는 *상한*이지 정해진 길이가 아니다. 끝내는 것은 사람이다 —
 * 폰을 빼면 거기서 큰 목소리가 끝나고, 그 뒤로는 메아리로 남는다.
 * 아무도 빼지 않으면 이 시간에 저절로 끝난다.
 *
 * /wall의 강조 렌더와 앱의 '지금 떠 있어요' 화면이 같은 초를 세야 한다.
 */
export const EMPHASIS_MS = 30_000;
export const EMPHASIS_SEC = EMPHASIS_MS / 1000;
